import { isValidUsername } from "../utils/validation";

/**
 * Reads the files from Instagram's "Download your information" export
 * (Accounts Center > Your information and permissions > Download your
 * information > Followers and following), in either format:
 *
 *   HTML  followers_1.html / following.html: one profile link per account
 *   JSON  the shapes below (the format has changed over the years, so all are accepted)
 *
 *   followers_1.json  [ { title: "", string_list_data: [ { href, value: "alice", timestamp } ] }, ... ]
 *   following.json    { relationships_following: [ { title: "bob", string_list_data: [ { href, timestamp } ] }, ... ] }
 *   plain             [ "alice", "bob" ]
 *
 * Nothing here touches the network or the DOM.
 */

/**
 * following / followers: the two lists that are compared.
 * recentlyUnfollowed: accounts YOU unfollowed (recently_unfollowed_profiles.html).
 * other: any other list of the download (favorites, close friends, ...); not used.
 */
export type ExportKind = "following" | "followers" | "recentlyUnfollowed" | "other" | "unknown";

export interface ExportParseResult {
  readonly kind: ExportKind;
  /** Usernames as written in the file, de-duplicated case-insensitively, in file order. */
  readonly usernames: readonly string[];
  /** Entries that did not contain a usable username. */
  readonly skipped: number;
  /** Day (YYYY-MM-DD) Instagram generated the file, when the file says so (the HTML export does, the JSON one does not). */
  readonly generatedOn?: string;
}

/** "Generated by <you> on <time datetime=\"2026-11-20T16:34Z\">" in the HTML export. */
export function generatedOnFromHtml(html: string): string | undefined {
  const match = /<time\b[^>]*\bdatetime\s*=\s*"(\d{4}-\d{2}-\d{2})/i.exec(html);
  return match === null ? undefined : match[1];
}

const PROFILE_PATH = /^\/(?:_u\/)?([A-Za-z0-9._]{1,30})\/?$/;

/** "https://www.instagram.com/_u/alice" -> "alice"; anything else -> null. */
export function usernameFromHref(href: unknown): string | null {
  if (typeof href !== "string") {
    return null;
  }
  try {
    const url = new URL(href);
    if (!/(^|\.)instagram\.com$/i.test(url.hostname)) {
      return null;
    }
    const match = PROFILE_PATH.exec(url.pathname);
    return match === null ? null : match[1];
  } catch {
    return null;
  }
}

function usernameFromEntry(entry: unknown): string | null {
  if (typeof entry === "string") {
    return isValidUsername(entry.trim()) ? entry.trim() : null;
  }
  if (typeof entry !== "object" || entry === null) {
    return null;
  }
  const record = entry as Record<string, unknown>;
  const list = Array.isArray(record.string_list_data) ? (record.string_list_data as unknown[]) : [];
  // The username is `value` in followers files, `title` in following files, and
  // always recoverable from the profile link.
  for (const item of list) {
    if (typeof item === "object" && item !== null) {
      const value = (item as Record<string, unknown>).value;
      if (typeof value === "string" && isValidUsername(value.trim())) {
        return value.trim();
      }
    }
  }
  if (typeof record.title === "string" && isValidUsername(record.title.trim())) {
    return record.title.trim();
  }
  for (const item of list) {
    if (typeof item === "object" && item !== null) {
      const fromHref = usernameFromHref((item as Record<string, unknown>).href);
      if (fromHref !== null) {
        return fromHref;
      }
    }
  }
  return null;
}

function collectEntries(parsed: unknown): { readonly entries: readonly unknown[]; readonly kind: ExportKind } {
  if (Array.isArray(parsed)) {
    return { entries: parsed, kind: "unknown" };
  }
  if (typeof parsed === "object" && parsed !== null) {
    const record = parsed as Record<string, unknown>;
    const keys = Object.keys(record);
    let kind: ExportKind = "unknown";
    const entries: unknown[] = [];
    for (const key of keys) {
      const value = record[key];
      if (!Array.isArray(value)) {
        continue;
      }
      if (/following/i.test(key)) {
        kind = "following";
      } else if (/follower/i.test(key)) {
        kind = "followers";
      }
      entries.push(...value);
    }
    return { entries, kind };
  }
  return { entries: [], kind: "unknown" };
}

/** Guess what a file is when its content does not say: by file name. */
export function kindFromFileName(name: string): ExportKind {
  if (/recently[ _-]?unfollowed/i.test(name)) {
    return "recentlyUnfollowed";
  }
  if (/following/i.test(name)) {
    return "following";
  }
  if (/follower/i.test(name)) {
    return "followers";
  }
  return "unknown";
}

// --- HTML export -------------------------------------------------------------

const HTML_ANCHOR = /<a\b[^>]*?\bhref\s*=\s*"([^"]*)"/gi;

/** "Followers" / "Following" from the page title or its first heading. */
function kindFromHtml(html: string): ExportKind {
  const title = /<title[^>]*>\s*([^<]*?)\s*<\/title>/i.exec(html);
  const heading = /<h1\b[^>]*>\s*([^<]*?)\s*<\/h1>/i.exec(html);
  for (const candidate of [title === null ? "" : title[1], heading === null ? "" : heading[1]]) {
    if (/^following$/i.test(candidate)) {
      return "following";
    }
    if (/^followers$/i.test(candidate)) {
      return "followers";
    }
    if (/^recently unfollowed/i.test(candidate)) {
      return "recentlyUnfollowed";
    }
  }
  return "unknown";
}

// Lists such as recently_unfollowed_profiles.html have no profile links: each entry is a
// small table  Name | ...  Username | <name>  followed by the date.
const HTML_USERNAME_CELL = /<td[^>]*>\s*Username\s*<\/td>\s*<td[^>]*>\s*([^<]*?)\s*<\/td>/gi;

function usernamesFromTables(html: string): { readonly usernames: string[]; readonly skipped: number } {
  const usernames: string[] = [];
  const seen: Record<string, true> = {};
  let skipped = 0;
  let match: RegExpExecArray | null;
  HTML_USERNAME_CELL.lastIndex = 0;
  while ((match = HTML_USERNAME_CELL.exec(html)) !== null) {
    const username = match[1];
    if (!isValidUsername(username)) {
      skipped++;
      continue;
    }
    const key = username.toLowerCase();
    if (seen[key] !== true) {
      seen[key] = true;
      usernames.push(username);
    }
  }
  return { usernames, skipped };
}

/** HTML export: every account is a link to its profile; nothing else on the page links to instagram.com/<name>. */
export function parseInstagramHtml(html: string, fileName: string = ""): ExportParseResult {
  const usernames: string[] = [];
  const seen: Record<string, true> = {};
  let skipped = 0;
  let match: RegExpExecArray | null;
  HTML_ANCHOR.lastIndex = 0;
  while ((match = HTML_ANCHOR.exec(html)) !== null) {
    const username = usernameFromHref(match[1].replace(/&amp;/g, "&"));
    if (username === null) {
      skipped++;
      continue;
    }
    const key = username.toLowerCase();
    if (seen[key] === true) {
      continue;
    }
    seen[key] = true;
    usernames.push(username);
  }
  const kind = kindFromHtml(html);
  if (usernames.length === 0) {
    const tables = usernamesFromTables(html);
    if (tables.usernames.length === 0) {
      throw new Error("No Instagram usernames were found in this file. Use followers_1.html / following.html from the Instagram export.");
    }
    const fromName = kind !== "unknown" ? kind : kindFromFileName(fileName);
    return { kind: fromName === "unknown" ? "other" : fromName, usernames: tables.usernames, skipped: tables.skipped, generatedOn: generatedOnFromHtml(html) };
  }
  return { kind: kind !== "unknown" ? kind : kindFromFileName(fileName), usernames, skipped, generatedOn: generatedOnFromHtml(html) };
}

const looksLikeHtml = (text: string, fileName: string): boolean =>
  /\.html?$/i.test(fileName) || /^\s*(<!doctype html|<html)/i.test(text.replace(/^﻿/, ""));

// --- entry point -------------------------------------------------------------

export function parseInstagramExport(text: string, fileName: string = ""): ExportParseResult {
  if (looksLikeHtml(text, fileName)) {
    return parseInstagramHtml(text, fileName);
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text.replace(/^﻿/, ""));
  } catch {
    throw new Error("This file is not valid JSON or HTML. Use followers_1.html / following.html (or the JSON versions) from your Instagram download.");
  }
  const { entries, kind: kindFromContent } = collectEntries(parsed);
  const usernames: string[] = [];
  const seen: Record<string, true> = {};
  let skipped = 0;
  for (const entry of entries) {
    const username = usernameFromEntry(entry);
    if (username === null) {
      skipped++;
      continue;
    }
    const key = username.toLowerCase();
    if (seen[key] === true) {
      continue;
    }
    seen[key] = true;
    usernames.push(username);
  }
  if (usernames.length === 0) {
    throw new Error("No Instagram usernames were found in this file.");
  }
  return {
    kind: kindFromContent !== "unknown" ? kindFromContent : kindFromFileName(fileName),
    usernames,
    skipped,
  };
}
